class EducationManager {
    /** Подбирает уроки по слабым навыкам и ещё не пройденные. */
    fun recommend(s: GameState, limit: Int = 3): List<Lesson> {
        val pending = Lessons.all.filter { it.id !in s.lessonsDone }
        if (pending.isEmpty()) return emptyList()
        return pending.sortedBy { s.skill(it.skill) }.take(limit)
    }

    fun nextLesson(s: GameState): Lesson? = recommend(s, 1).firstOrNull()

    /** Урок засчитывается при ≥ 2/3 правильных ответов. */
    fun complete(s: GameState, lessonId: String, correct: Int, total: Int): GameState {
        val lesson = Lessons.all.first { it.id == lessonId }
        val pass = correct * 3 >= total * 2
        var n = s.copy(practiceRight = s.practiceRight + correct, practiceTotal = s.practiceTotal + total)
        n = n.skillAdd(lesson.skill, if (pass) 4 else -1)
        if (pass && lesson.id !in n.lessonsDone) n = n.copy(lessonsDone = n.lessonsDone + lesson.id).gain(30)
        return n
    }
}
