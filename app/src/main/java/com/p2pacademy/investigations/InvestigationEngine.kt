    val count: Int get() = templates.size

    private fun build(t: Tpl, id: String, seed: Long, r: Random): CaseFile {
        val c = Ctx(r)
        val q1 = Question("Расследование", "Где возникла проблема?", problemOpts, t.problem, t.why)
        val q2 = Question("Расследование", "Кто допустил нарушение?", whoOpts, t.violator, t.why)
        val q3 = Question("Расследование", "Есть ли мошенничество?", listOf("Да", "Нет"), if (t.fraud) 0 else 1, t.why)
        val wrong = listOf("Отпустить актив / продолжить как просит собеседник", "Отменить заявку и продолжить общение вне площадки", "Переслать подтверждение и подождать").shuffled(r)
        val opts = (listOf(t.safest) + wrong).shuffled(r)
        val q4 = Question("Расследование", "Какое решение безопаснее?", opts, opts.indexOf(t.safest), t.why)
        return CaseFile(id, t.title, t.level, t.evidence(c), listOf(q1, q2, q3, q4))
    }

    /** 20 фиксированных дел с стабильными ID. */
    val library: List<CaseFile> by lazy {
        templates.mapIndexed { i, t -> build(t, "c${i + 1}", 100L + i, rng(100L + i, i.toLong())) }
    }

    /** Новое дело на основе шаблона. */
    fun generate(seed: Long, index: Int): CaseFile {
        val r = rng(seed, index.toLong(), 999L)
        val t = templates[r.nextInt(templates.size)]
        return build(t, "g$seed-$index", seed, r)
    }

    /** Находит дело по ID: "cN" — библиотека, "g<seed>-<index>" — сгенерированное. */
    fun find(id: String): CaseFile? {
        if (id.startsWith("c")) return library.find { it.id == id }
        if (id.startsWith("g")) {
            val parts = id.drop(1).split("-")
            val seed = parts.getOrNull(0)?.toLongOrNull() ?: return null
            val idx = parts.getOrNull(1)?.toIntOrNull() ?: return null
            return generate(seed, idx)
        }
        return null
    }

    fun grade(case: CaseFile, answers: List<Int>): Int =
        case.questions.indices.count { answers.getOrNull(it) == case.questions[it].correct } * 100 / case.questions.size

    fun apply(s: GameState, case: CaseFile, scorePct: Int): GameState {
        val old = s.casesDone[case.id] ?: -1
        var n = s.copy(casesDone = s.casesDone + (case.id to maxOf(old, scorePct)))
        if (old < 0) n = n.gain(20 + case.level * 10 * scorePct / 100)
        return n.skillAdd(Skill.SAFETY, if (scorePct >= 75) 2 else -1).skillAdd(Skill.VERIFY, if (scorePct >= 75) 2 else 0)
    }
